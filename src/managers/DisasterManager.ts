import {Plugins, Physics, Scene} from "phaser";
import type {AsteroidBeltData} from "../gameData/AsteroidBeltData.ts";
import type {TimeFieldData} from "../gameData/TimeFieldData.ts";
import type {BlackHoleData} from "../gameData/BlackHoleData.ts";
import type {SolarFlareData} from "../gameData/SolarFlareData.ts";
import type {CryogenicData} from "../gameData/CryogenicData.ts";
import type ITimeScalable from "../components/ITimeScalable.ts";
import Asteroid from "../entities/Asteroid.ts";
import Player from "../entities/Player.ts";
import Enemy from "../entities/Enemy.ts";
import BlackHole from "../entities/BlackHole.ts";
import SolarFlare from "../entities/SolarFlare.ts";
import Health from "../components/Health.ts";
import GroupUtils from "../utils/GroupUtils.ts";
import GameConstants from "../GameConstants.ts";

// Direction the belt travels in. A belt moving right (x: 1) spawns beyond the left border
const BELT_DIRECTIONS: readonly Readonly<{ x: number, y: number }>[] = [
    {x: 1, y: 0}, {x: -1, y: 0}, {x: 0, y: 1}, {x: 0, y: -1}
];

export default class DisasterManager extends Plugins.ScenePlugin {
    public static readonly PLUGIN_KEY: string = 'DisasterManager';
    public static readonly MAPPING_NAME: string = 'disasterManager';

    // Delay (ms) between two automatic disasters: shrinks linearly from START to MIN
    // over RAMP_DURATION, then stays at MIN
    private static readonly DISASTER_INTERVAL_START: number = 30000;
    private static readonly DISASTER_INTERVAL_MIN: number = 10000;
    private static readonly DISASTER_RAMP_DURATION: number = 180000; // 3 min
    // After this time (ms since the start of the game), disasters come in pairs
    private static readonly DOUBLE_DISASTER_TIME: number = 120000; // 2 min
    // The player can't be hit by asteroids again during this time (ms)
    private static readonly PLAYER_HIT_COOLDOWN: number = 1000;
    // Texture keys: 'timefield_slow', 'timefield_icon_slow', 'timefield_fast', 'timefield_icon_fast'
    private static readonly TIME_FIELD_TEXTURE_PREFIX: string = 'timefield_';
    private static readonly TIME_FIELD_ICON_PREFIX: string = 'timefield_icon_';
    // Delay (ms) between two refreshes of the time scales (time fields and cryogenic effect)
    private static readonly TIME_SCALE_UPDATE_DELAY: number = 50;
    // Frost texture generated by code (no image needed)
    private static readonly FROST_TEXTURE_KEY: string = 'cryo_frost';

    private readonly _asteroidBeltData: AsteroidBeltData = {
        count: 60,
        batchSize: 3,
        duration: 16000,
        bandWidth: 1000,
        spawnMargin: 400,
        spawnDepth: 300,
        minSpeed: 400,
        maxSpeed: 700,
        minScale: 0.8,
        maxScale: 1.6,
        maxSpin: 90,
        damage: 1,
    };

    private readonly _timeFieldData: TimeFieldData = {
        radius: 450,
        warningDuration: 3000,
        duration: 12000,
        slowScale: 0.4,
        fastScale: 1.8,
        minDistanceFromPlayer: 200,
        maxDistanceFromPlayer: 700,
    };

    private readonly _blackHoleData: BlackHoleData = {
        duration: 15000,
        spawnDuration: 1500,
        startSize: 200,
        endSize: 900,
        killRadiusRatio: 0.12,
        pullRadiusRatio: 2.5,
        maxPullSpeed: 0.6,
        minDistanceFromPlayer: 500,
        maxDistanceFromPlayer: 900,
    };

    private readonly _solarFlareData: SolarFlareData = {
        warningDuration: 2500,
        minDuration: 5000,
        maxDuration: 10000,
        thickness: 500,
        hitMargin: 45,
        damage: 1,
        minDistanceFromPlayer: 100,
        maxDistanceFromPlayer: 500,
    };

    private readonly _cryogenicData: CryogenicData = {
        duration: 10000,
        fadeDuration: 1000,
        playerTimeScale: 0.2,
        enemyTimeScale: 0.9,
    };

    private _player: Player;
    private _timeFieldActive: boolean = false;
    private _asteroids: Physics.Arcade.Group;
    private _nextPlayerHitTime: number = 0;
    private _disasterStartTime: number = 0;
    private _enemies: Physics.Arcade.Group;
    private _blackHole: BlackHole | undefined;
    private _cryogenicActive: boolean = false;
    // The active time field, if any: the zone and the time scale applied inside it
    private _timeField: { x: number, y: number, radius: number, scale: number } | undefined;
    private _timeScaleEvent: Phaser.Time.TimerEvent | undefined;

    constructor(scene: Scene, pluginManager: Plugins.PluginManager) {
        super(scene, pluginManager, DisasterManager.PLUGIN_KEY);

        console.log("[DisasterManager] Initialized");
    }

    destroy() {
        super.destroy();

        console.log("[DisasterManager] Destroyed");
    }

    public initDisasters(player: Player, enemies: Physics.Arcade.Group) {
        this._asteroids = this.scene!.physics.add.group({
            classType: Asteroid,
            defaultKey: GameConstants.ASTEROID_TEXTURE_PREFIX + '0',
            maxSize: 128
        });
        GroupUtils.populate(64, this._asteroids);
        this._nextPlayerHitTime = 0;
        this._player = player;
        this._enemies = enemies;
        this._blackHole = undefined;
        this._timeFieldActive = false;
        this._cryogenicActive = false;
        this._timeField = undefined;
        this._timeScaleEvent = undefined;

        // Overlap, not collider: asteroids never get pushed around
        this.scene!.physics.add.overlap(this._asteroids, enemies, (_asteroid, enemy) => {
            const enemyHealth = (enemy as Enemy).getComponent(Health);
            enemyHealth?.damage(enemyHealth.max);
        });

        this.scene!.physics.add.overlap(player, this._asteroids, (_playerObj, asteroidObj) => {
            this.damagePlayer((asteroidObj as Asteroid).damage);
        });

        // Spawn rate ramps up over time. initDisasters runs on every (re)start of the scene,
        // so the ramp is reset at the end of each game
        this._disasterStartTime = this.scene!.time.now;
        this.scheduleNextDisaster();

        console.log("[DisasterManager] Disasters initialized");
    }

    // Damage from asteroids and solar flares, sharing the same protection time
    private damagePlayer(amount: number) {
        // Overlaps fire every frame while touching: without a cooldown the player would die instantly
        if (this.scene!.time.now < this._nextPlayerHitTime)
            return;
        this._nextPlayerHitTime = this.scene!.time.now + DisasterManager.PLAYER_HIT_COOLDOWN;

        this._player.getComponent(Health)?.damage(amount);

        this.scene!.cameras.main.shake(150, 0.02);
        // Blink during the cooldown (5 x 200ms) so the player sees they are protected
        this.scene!.tweens.add({targets: this._player, alpha: 0.3, duration: 100, yoyo: true, repeat: 4});
    }

    private scheduleNextDisaster() {
        const elapsed: number = this.scene!.time.now - this._disasterStartTime;
        const progress: number = Phaser.Math.Clamp(elapsed / DisasterManager.DISASTER_RAMP_DURATION, 0, 1);
        const delay: number = Phaser.Math.Linear(
            DisasterManager.DISASTER_INTERVAL_START, DisasterManager.DISASTER_INTERVAL_MIN, progress);

        // One-shot timers instead of a loop: the delay is recomputed each time.
        // The scene clock removes pending timers when the scene stops or restarts
        this.scene!.time.delayedCall(delay, () => {
            this.startRandomDisaster();
            this.scheduleNextDisaster();
        });
    }

    // One disaster, or two at once after DOUBLE_DISASTER_TIME. The two are always different.
    // A disaster that can't start (already active, e.g. a time field) is skipped for another one
    private startRandomDisaster() {
        const elapsed: number = this.scene!.time.now - this._disasterStartTime;
        const count: number = elapsed >= DisasterManager.DOUBLE_DISASTER_TIME ? 2 : 1;

        const starters: (() => boolean)[] = Phaser.Utils.Array.Shuffle([
            () => this.startAsteroidBelt(),
            () => this.startTimeField(),
            () => this.startBlackHole(),
            () => this.startSolarFlare(),
            () => this.startCryogenic(),
        ]);

        let started: number = 0;
        for (const start of starters) {
            if (started >= count)
                break;

            if (start())
                started++;
        }
    }

    public startAsteroidBelt(): boolean {
        const data: AsteroidBeltData = this._asteroidBeltData;
        const direction = Phaser.Utils.Array.GetRandom(BELT_DIRECTIONS as { x: number, y: number }[]);

        // The band is placed along the axis perpendicular to the direction, and kept inside the arena
        const crossLength: number = direction.x !== 0 ? GameConstants.ARENA_HEIGHT : GameConstants.ARENA_WIDTH;
        const bandWidth: number = Math.min(data.bandWidth, crossLength);
        const bandStart: number = Phaser.Math.Between(0, crossLength - bandWidth);

        // Spread the spawns over time: no lag spike, and a belt that "flows" instead of a wall
        const batchCount: number = Math.ceil(data.count / data.batchSize);
        let remaining: number = data.count;
        this.scene!.time.addEvent({
            delay: data.duration / batchCount,
            repeat: batchCount - 1,
            callback: () => {
                const quantity: number = Math.min(data.batchSize, remaining);
                for (let i: number = 0; i < quantity; i++)
                    this.spawnAsteroid(direction, bandStart, bandWidth);
                remaining -= quantity;
            }
        });

        // Hook for a future warning UI
        this.game!.events.emit(GameConstants.Events.ASTEROID_BELT_STARTED_EVENT, direction, bandStart, bandWidth);

        console.log("[DisasterManager] Asteroid belt started", direction);

        return true;
    }

    // A zone that slows down or accelerates everything inside it: player, enemies, bullets and asteroids
    // Without argument, the type is random. The argument is used by the dev cheat keys
    public startTimeField(forcedType?: 'slow' | 'fast'): boolean {
        // One field at a time
        if (this._timeFieldActive)
            return false;
        this._timeFieldActive = true;

        const data: TimeFieldData = this._timeFieldData;
        const isSlow: boolean = forcedType ? forcedType === 'slow' : Phaser.Math.Between(0, 1) === 0;
        const scale: number = isSlow ? data.slowScale : data.fastScale;

        // Appear around the player, or it would most likely be somewhere on the arena the camera never shows
        const offset: Phaser.Math.Vector2 = Phaser.Math.RandomXY(new Phaser.Math.Vector2(),
            Phaser.Math.FloatBetween(data.minDistanceFromPlayer, data.maxDistanceFromPlayer));
        const x: number = Phaser.Math.Clamp(this._player.x + offset.x, data.radius, GameConstants.ARENA_WIDTH - data.radius);
        const y: number = Phaser.Math.Clamp(this._player.y + offset.y, data.radius, GameConstants.ARENA_HEIGHT - data.radius);

        // Drawn over the world. The rift spins (slowly or quickly depending on the type) and "breathes", the icon stays upright
        const type: string = isSlow ? 'slow' : 'fast';
        const bubble = this.scene!.add.image(x, y, DisasterManager.TIME_FIELD_TEXTURE_PREFIX + type)
            .setDisplaySize(data.radius * 2, data.radius * 2).setDepth(10);
        const icon = this.scene!.add.image(x, y, DisasterManager.TIME_FIELD_ICON_PREFIX + type)
            .setDisplaySize(data.radius * 0.5, data.radius * 0.5).setDepth(11);
        const visuals = [bubble, icon];

        // Warning phase: pulsing, no effect yet
        const pulse = this.scene!.tweens.add({
            targets: visuals, alpha: {from: 0.2, to: 0.7}, duration: 300, yoyo: true, repeat: -1
        });

        this.scene!.time.delayedCall(data.warningDuration, () => {
            pulse.stop();
            visuals.forEach(visual => visual.setAlpha(1));
            const spin = this.scene!.tweens.add({
                targets: bubble, angle: isSlow ? -360 : 360, duration: isSlow ? 20000 : 3000, repeat: -1
            });
            // Unstable rift: the size slightly oscillates, faster for an accelerated field
            const baseScale: number = bubble.scaleX;
            const breath = this.scene!.tweens.add({
                targets: bubble, scale: {from: baseScale * 0.96, to: baseScale * 1.04},
                duration: isSlow ? 1400 : 500, yoyo: true, repeat: -1, ease: 'Sine.easeInOut'
            });

            // Active phase: rescale everything inside, 20 times per second
            this._timeField = {x, y, radius: data.radius, scale};
            this.startTimeScaleUpdates();

            this.scene!.time.delayedCall(data.duration, () => {
                this._timeField = undefined; // Back to normal speed for everyone (unless frozen)
                this.stopTimeScaleUpdates();
                this._timeFieldActive = false;

                spin.stop();
                breath.stop();
                this.scene!.tweens.add({
                    targets: visuals, alpha: 0, duration: 500,
                    onComplete: () => visuals.forEach(visual => visual.destroy())
                });
            });
        });

        console.log("[DisasterManager] Time field started", isSlow ? "(slow)" : "(fast)");

        return true;
    }

    // A fire laser crossing the whole arena, staying at the same place for several seconds.
    // The beam appears around the player (or it would most likely be somewhere the camera never shows),
    // and its zone is shown first (warning phase)
    public startSolarFlare(): boolean {
        const data: SolarFlareData = this._solarFlareData;
        const horizontal: boolean = Phaser.Math.Between(0, 1) === 0;

        // Position on the axis perpendicular to the beam: near the player, kept inside the arena
        const crossLength: number = horizontal ? GameConstants.ARENA_HEIGHT : GameConstants.ARENA_WIDTH;
        const playerCross: number = horizontal ? this._player.y : this._player.x;
        const side: number = Phaser.Math.Between(0, 1) === 0 ? -1 : 1;
        const offset: number = side * Phaser.Math.FloatBetween(data.minDistanceFromPlayer, data.maxDistanceFromPlayer);
        const crossCenter: number = Phaser.Math.Clamp(playerCross + offset, data.thickness / 2, crossLength - data.thickness / 2);

        // The laser adds itself to the scene and destroys itself once it has shut down
        new SolarFlare(this.scene!, data, horizontal, crossCenter, this._player, this._enemies,
            (damage: number) => this.damagePlayer(damage));

        console.log("[DisasterManager] Solar flare started", horizontal ? "(horizontal)" : "(vertical)");

        return true;
    }

    // A cold wave over the whole arena: the player is slowed down (and so is his fire rate, which follows
    // his time scale) and the enemies too, less. Asteroids, bullets and the other disasters are not affected.
    // It adds up with a time field: both scales are multiplied
    public startCryogenic(): boolean {
        // One cold wave at a time
        if (this._cryogenicActive)
            return false;
        this._cryogenicActive = true;

        const data: CryogenicData = this._cryogenicData;
        const camera = this.scene!.cameras.main;
        DisasterManager.ensureFrostTexture(this.scene!, camera.width, camera.height);

        // Fixed on the screen, over the world: a cold tint and frost creeping from the borders
        const tint = this.scene!.add.rectangle(0, 0, camera.width, camera.height, 0x66ccff, 0.18)
            .setOrigin(0).setScrollFactor(0).setDepth(20);
        const frost = this.scene!.add.image(0, 0, DisasterManager.FROST_TEXTURE_KEY)
            .setOrigin(0).setScrollFactor(0).setDepth(21);
        const visuals = [tint, frost];
        visuals.forEach(visual => visual.setAlpha(0));

        camera.flash(300, 150, 220, 255);
        this.startTimeScaleUpdates();

        this.scene!.tweens.add({
            targets: visuals, alpha: 1, duration: data.fadeDuration,
            onComplete: () => {
                // The cold tint breathes while the effect lasts
                this.scene!.tweens.add({
                    targets: tint, alpha: {from: 1, to: 0.6}, duration: 900, yoyo: true, repeat: -1,
                    ease: 'Sine.easeInOut'
                });
            }
        });

        this.scene!.time.delayedCall(data.duration, () => {
            // Everyone gets back to normal speed while the frost melts
            this._cryogenicActive = false;
            this.stopTimeScaleUpdates();

            this.scene!.tweens.killTweensOf(visuals);
            this.scene!.tweens.add({
                targets: visuals, alpha: 0, duration: data.fadeDuration,
                onComplete: () => visuals.forEach(visual => visual.destroy())
            });
        });

        console.log("[DisasterManager] Cryogenic started");

        return true;
    }

    // Transparent in the middle, icy on the borders
    private static ensureFrostTexture(scene: Scene, width: number, height: number) {
        if (scene.textures.exists(DisasterManager.FROST_TEXTURE_KEY))
            return;

        const texture = scene.textures.createCanvas(DisasterManager.FROST_TEXTURE_KEY, width, height);
        if (!texture)
            return;

        const context = texture.getContext();
        const gradient = context.createRadialGradient(width / 2, height / 2, Math.min(width, height) * 0.2,
            width / 2, height / 2, Math.hypot(width, height) / 2);
        gradient.addColorStop(0, 'rgba(150, 220, 255, 0)');
        gradient.addColorStop(0.6, 'rgba(150, 220, 255, 0.15)');
        gradient.addColorStop(1, 'rgba(220, 245, 255, 0.7)');
        context.fillStyle = gradient;
        context.fillRect(0, 0, width, height);

        texture.refresh();
    }

    // A black hole that slowly grows, pulls the player and the enemies towards it and kills what touches its core
    public startBlackHole(): boolean {
        // One black hole at a time
        if (this._blackHole?.active)
            return false;

        const data: BlackHoleData = this._blackHoleData;

        // Appear around the player, or it would most likely be somewhere on the arena the camera never shows.
        // Kept far enough from the arena borders for its final size
        const margin: number = data.endSize / 2;
        const offset: Phaser.Math.Vector2 = Phaser.Math.RandomXY(new Phaser.Math.Vector2(),
            Phaser.Math.FloatBetween(data.minDistanceFromPlayer, data.maxDistanceFromPlayer));
        const x: number = Phaser.Math.Clamp(this._player.x + offset.x, margin, GameConstants.ARENA_WIDTH - margin);
        const y: number = Phaser.Math.Clamp(this._player.y + offset.y, margin, GameConstants.ARENA_HEIGHT - margin);

        this._blackHole = new BlackHole(this.scene!, x, y, data, this._player, this._enemies);
        this._blackHole.start();

        console.log("[DisasterManager] Black hole started");

        return true;
    }

    // The time scales are refreshed from one place, while a time field or the cryogenic effect is active:
    // each of them used to reset everything outside of its zone to normal speed, and would cancel the other
    private startTimeScaleUpdates() {
        this.applyTimeScales();

        if (this._timeScaleEvent)
            return;

        this._timeScaleEvent = this.scene!.time.addEvent({
            delay: DisasterManager.TIME_SCALE_UPDATE_DELAY,
            loop: true,
            callback: this.applyTimeScales,
            callbackScope: this
        });
    }

    // Refreshes once more (to give back the normal speed), and stops refreshing when nothing is active anymore
    private stopTimeScaleUpdates() {
        this.applyTimeScales();

        if (this._timeField || this._cryogenicActive)
            return;

        this._timeScaleEvent?.remove();
        this._timeScaleEvent = undefined;
    }

    // Time scale of a target = time field (inside its zone) x cryogenic effect (player and enemies only)
    private applyTimeScales() {
        const field = this._timeField;
        const radiusSq: number = field ? field.radius * field.radius : 0;

        // Only enabled bodies are in the world: pooled (disabled) objects are skipped
        for (const body of this.scene!.physics.world.bodies.entries) {
            const target = body.gameObject as unknown as ITimeScalable | null;
            if (!target || typeof target.setTimeScale !== 'function')
                continue;

            let scale: number = 1;
            if (field) {
                const dx: number = body.center.x - field.x;
                const dy: number = body.center.y - field.y;
                if (dx * dx + dy * dy <= radiusSq)
                    scale = field.scale;
            }
            scale *= this.cryogenicScale(target);

            if (target.timeScale !== scale)
                target.setTimeScale(scale);
        }
    }

    private cryogenicScale(target: ITimeScalable): number {
        if (!this._cryogenicActive)
            return 1;

        if (target === this._player)
            return this._cryogenicData.playerTimeScale;
        if (target instanceof Enemy)
            return this._cryogenicData.enemyTimeScale;

        return 1;
    }

    private spawnAsteroid(direction: { x: number, y: number }, bandStart: number, bandWidth: number) {
        const asteroid = this._asteroids.get() as Asteroid | null;
        if (!asteroid)
            return;

        const data: AsteroidBeltData = this._asteroidBeltData;

        // Beyond the arena border: the camera is bound to the arena, so the player can never see the spawn
        const offset: number = data.spawnMargin + Phaser.Math.Between(0, data.spawnDepth);
        const cross: number = bandStart + Phaser.Math.Between(0, bandWidth);
        let x: number, y: number;
        if (direction.x !== 0) {
            x = direction.x > 0 ? -offset : GameConstants.ARENA_WIDTH + offset;
            y = cross;
        } else {
            x = cross;
            y = direction.y > 0 ? -offset : GameConstants.ARENA_HEIGHT + offset;
        }

        // Same direction for the whole belt, only the speed varies
        const speed: number = Phaser.Math.FloatBetween(data.minSpeed, data.maxSpeed);
        const texture: string = GameConstants.ASTEROID_TEXTURE_PREFIX
            + Phaser.Math.Between(0, GameConstants.ASTEROID_TEXTURE_COUNT - 1);

        asteroid.enable(x, y, direction.x * speed, direction.y * speed, texture,
            Phaser.Math.FloatBetween(data.minScale, data.maxScale),
            Phaser.Math.FloatBetween(-data.maxSpin, data.maxSpin), data.damage);
    }
}